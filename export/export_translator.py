def translate_export(df, lang="bg"):
    df = df.copy()
    translations = EXPORT_TRANSLATIONS.get(lang, EXPORT_TRANSLATIONS["en"])

    df.rename(columns=translations["columns"], inplace=True)
    values = translations["values"]

    for column in df.columns:
        df[column] = df[column].replace(values)

    return df